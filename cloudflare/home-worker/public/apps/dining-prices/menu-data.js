export const dishKey=name=>name.normalize('NFKC').replace(/\s/g,'').replace(/^海老$/,'エビ').replace(/^焼マシュマロ$/,'焼きマシュマロ').replace(/^お子様/,'お子さま').replace(/^玉子スープ$/,'たまごスープ');
export function uniqueDishes(dishes){
 const seen=new Set();
 return dishes.filter(({name})=>{
  const key=dishKey(name);
  if(seen.has(key))return false;
  seen.add(key);
  return true;
 });
}
